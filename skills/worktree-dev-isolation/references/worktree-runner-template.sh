#!/usr/bin/env bash
# ==============================================================================
# Universal Worktree Runtime Runner  (install as scripts/worktree-dev.sh)
# ==============================================================================
# Stack-agnostic, zero-LLM, deterministic slot/port allocator and process runner.
#
#   worktree-dev.sh up [-d|--detach] [--port N]   sync files, start deps (+ app)
#   worktree-dev.sh stop                          stop app + containers (data kept)
#   worktree-dev.sh down [--purge]                remove containers (--purge: volumes + state)
#   worktree-dev.sh clean                         = down --purge
#   worktree-dev.sh sync                          inherit .worktreeinclude files from main
#   worktree-dev.sh info                          slot, ports, status
#   worktree-dev.sh env [--port N]                `export` lines for eval
#   worktree-dev.sh test                          run WT_TEST_CMD (or a health check)
#
# Per-project settings go in scripts/worktree-dev.conf (sourced if present) or in
# the environment. Do not edit this file for project tweaks. Variables:
#   WT_PROJECT_NAME        compose/DB name prefix           (default: main checkout dir name)
#   WT_CONTAINER_ENGINE    docker | podman | none           (default: docker)
#   WT_COMPOSE_FILE        compose file                     (default: first of compose.y(a)ml, docker-compose.y(a)ml)
#   WT_DB_SERVICE          compose service started by `up`  (default: db; empty = all services)
#   WT_APP_CMD             command that runs the app        (empty = only prepare deps/env)
#   WT_TEST_CMD            command for `test`               (empty = health check)
#   WT_HEALTH_URL          health URL, {port} substituted   (empty = TCP check on app port)
#   WT_HEALTH_TIMEOUT      seconds to wait after `up -d`    (default: 60)
#   WT_CANONICAL_APP_PORT / WT_CANONICAL_DB_PORT   ports used by the main checkout (slot 0)
#   WT_APP_BASE_PORT / WT_DB_BASE_PORT             linked worktrees use BASE + slot (1..99)
#   WT_ENV_APP_PORT_NAME / WT_ENV_DB_PORT_NAME / WT_ENV_DB_URL_NAME   exported variable names
#   WT_DB_URL_TEMPLATE     {port} {project} {db} substituted; set to "" to disable
#
# State lives in .worktree-dev/ (must be git-ignored). It is sticky: the slot and
# ports chosen on first use are reused until `clean`. Peers' slots are respected.
# ==============================================================================

set -euo pipefail

# --- 1. Helpers ---------------------------------------------------------------
log()  { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

WT_ROOT="${WT_ROOT:-$(git rev-parse --show-toplevel 2>/dev/null || pwd -P)}"
cd "$WT_ROOT"

path_hash() { printf '%s' "$1" | cksum | cut -d' ' -f1; }

sanitize() { # lowercase, [a-z0-9_-] only
  printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9_\n-' '-' | sed 's/^-*//; s/-*$//'
}

is_main_worktree() {
  local gd gc
  gd=$(git rev-parse --git-dir 2>/dev/null) || return 0           # not a git repo: treat as main
  gc=$(git rev-parse --git-common-dir 2>/dev/null) || return 0
  [ "$(cd "$gd" && pwd -P)" = "$(cd "$gc" && pwd -P)" ]
}

main_worktree_path() {
  git worktree list --porcelain 2>/dev/null | sed -n 's/^worktree //p' | head -n 1
}

# --- 2. Configuration ---------------------------------------------------------
WT_CONFIG="${WT_CONFIG:-$WT_ROOT/scripts/worktree-dev.conf}"
if [ -f "$WT_CONFIG" ]; then
  # shellcheck disable=SC1090
  . "$WT_CONFIG"
fi

MAIN_ROOT="$(main_worktree_path)"; MAIN_ROOT="${MAIN_ROOT:-$WT_ROOT}"
PROJECT_NAME="$(sanitize "${WT_PROJECT_NAME:-$(basename "$MAIN_ROOT")}")"
CONTAINER_ENGINE="${WT_CONTAINER_ENGINE:-docker}"
DB_SERVICE="${WT_DB_SERVICE-db}"
APP_CMD="${WT_APP_CMD:-}"
TEST_CMD="${WT_TEST_CMD:-}"
HEALTH_URL="${WT_HEALTH_URL:-}"
HEALTH_TIMEOUT="${WT_HEALTH_TIMEOUT:-60}"

CANONICAL_APP_PORT="${WT_CANONICAL_APP_PORT:-8080}"
CANONICAL_DB_PORT="${WT_CANONICAL_DB_PORT:-5432}"
APP_BASE_PORT="${WT_APP_BASE_PORT:-8100}"
DB_BASE_PORT="${WT_DB_BASE_PORT:-15500}"
SLOT_COUNT=100

ENV_APP_PORT_NAME="${WT_ENV_APP_PORT_NAME:-PORT}"
ENV_DB_PORT_NAME="${WT_ENV_DB_PORT_NAME:-DB_PORT}"
ENV_DB_URL_NAME="${WT_ENV_DB_URL_NAME:-DATABASE_URL}"
# (unset = default template; set to "" to disable. Not ${VAR-default}: its "}" would end the expansion.)
if [ -z "${WT_DB_URL_TEMPLATE+x}" ]; then
  DB_URL_TEMPLATE='postgres://app:app@127.0.0.1:{port}/{db}'
else
  DB_URL_TEMPLATE=$WT_DB_URL_TEMPLATE
fi

COMPOSE_FILE_PATH=""
if [ "$CONTAINER_ENGINE" != "none" ]; then
  if [ -n "${WT_COMPOSE_FILE:-}" ]; then
    COMPOSE_FILE_PATH="$WT_COMPOSE_FILE"
  else
    for f in compose.yaml compose.yml docker-compose.yaml docker-compose.yml; do
      if [ -f "$WT_ROOT/$f" ]; then COMPOSE_FILE_PATH="$WT_ROOT/$f"; break; fi
    done
  fi
  [ -f "$COMPOSE_FILE_PATH" ] || COMPOSE_FILE_PATH=""
fi

WT_STATE_DIR="$WT_ROOT/.worktree-dev"
WT_SLOT_FILE="$WT_STATE_DIR/slot.env"
WT_PID_FILE="$WT_STATE_DIR/app.pid"
WT_LOG_FILE="$WT_STATE_DIR/app.log"
WT_COMPOSE_PROJECT="${PROJECT_NAME}-wt-$(sanitize "$(basename "$WT_ROOT")")-$(printf '%06x' $(($(path_hash "$WT_ROOT") % 16777216)))"

# --- 3. Network / process helpers ---------------------------------------------
port_busy() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

app_alive() {
  [ -f "$WT_PID_FILE" ] || return 1
  kill -0 "$(cat "$WT_PID_FILE")" 2>/dev/null
}

stop_app() {
  app_alive || { rm -f "$WT_PID_FILE"; return 0; }
  local pid i; pid=$(cat "$WT_PID_FILE")
  log "Stopping app (pid $pid)..."
  kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null || true
  for ((i = 0; i < 20; i++)); do
    kill -0 "$pid" 2>/dev/null || break
    sleep 0.5
  done
  if kill -0 "$pid" 2>/dev/null; then
    warn "app did not exit after SIGTERM, sending SIGKILL"
    kill -KILL -- "-$pid" 2>/dev/null || kill -KILL "$pid" 2>/dev/null || true
  fi
  rm -f "$WT_PID_FILE"
}

health_ok() {
  if [ -n "$HEALTH_URL" ] && command -v curl >/dev/null 2>&1; then
    curl -fsS -o /dev/null --max-time 2 "${HEALTH_URL//\{port\}/$APP_PORT}" 2>/dev/null
  else
    port_busy "$APP_PORT"
  fi
}

wait_healthy() {
  local i
  for ((i = 0; i < HEALTH_TIMEOUT; i++)); do
    # The child writes its own pid file asynchronously: tolerate its absence for a few seconds.
    if ! app_alive && { [ -f "$WT_PID_FILE" ] || [ "$i" -ge 5 ]; }; then
      warn "app exited early; last log lines:"; tail -n 20 "$WT_LOG_FILE" >&2 || true; return 1
    fi
    if health_ok; then return 0; fi
    sleep 1
  done
  warn "app not healthy after ${HEALTH_TIMEOUT}s"
  return 1
}

# --- 4. Containers ------------------------------------------------------------
check_tools() {
  [ -n "$COMPOSE_FILE_PATH" ] || return 0
  case "$CONTAINER_ENGINE" in
    docker)
      command -v docker >/dev/null 2>&1 || die "docker is required"
      docker compose version >/dev/null 2>&1 || die "docker compose (v2) is required" ;;
    podman)
      command -v podman >/dev/null 2>&1 || die "podman is required"
      command -v podman-compose >/dev/null 2>&1 || podman compose version >/dev/null 2>&1 \
        || die "podman-compose (or 'podman compose') is required" ;;
    *) die "unknown WT_CONTAINER_ENGINE: $CONTAINER_ENGINE (docker|podman|none)" ;;
  esac
}

compose() {
  [ -n "$COMPOSE_FILE_PATH" ] || return 0
  case "$CONTAINER_ENGINE" in
    docker) docker compose -p "$WT_COMPOSE_PROJECT" -f "$COMPOSE_FILE_PATH" "$@" ;;
    podman)
      if command -v podman-compose >/dev/null 2>&1; then
        podman-compose -p "$WT_COMPOSE_PROJECT" -f "$COMPOSE_FILE_PATH" "$@"
      else
        podman compose -p "$WT_COMPOSE_PROJECT" -f "$COMPOSE_FILE_PATH" "$@"
      fi ;;
  esac
}

# --- 5. Untracked files inheritance (.worktreeinclude) ------------------------
# One entry per line; `#` comments. Prefix `link:` to symlink instead of copy.
# Directories are supported. Existing files in the worktree are never overwritten.
include_entries() {
  local line
  while IFS= read -r line || [ -n "$line" ]; do
    line=${line%$'\r'}
    line="${line#"${line%%[![:space:]]*}"}"; line="${line%"${line##*[![:space:]]}"}"
    case "$line" in ''|'#'*) continue ;; esac
    printf '%s\n' "$line"
  done < "$1"
}

sync_untracked() {
  is_main_worktree && return 0
  [ "$MAIN_ROOT" != "$WT_ROOT" ] && [ -d "$MAIN_ROOT" ] || return 0

  local entries=() list=""
  if   [ -f "$WT_ROOT/.worktreeinclude" ];   then list="$WT_ROOT/.worktreeinclude"
  elif [ -f "$MAIN_ROOT/.worktreeinclude" ]; then list="$MAIN_ROOT/.worktreeinclude"; fi
  if [ -n "$list" ]; then
    while IFS= read -r l; do entries+=("$l"); done < <(include_entries "$list")
  else
    entries=(.env .env.local .npmrc .tool-versions .mise.toml)
  fi

  local n=0 entry rel mode src dst
  for entry in ${entries[@]+"${entries[@]}"}; do
    mode="copy"; rel=$entry
    case "$entry" in link:*) mode="link"; rel=${entry#link:}; rel="${rel#"${rel%%[![:space:]]*}"}" ;; esac
    rel=${rel%/}
    case "/$rel/" in */../*) warn "ignoring unsafe .worktreeinclude entry: $entry"; continue ;; esac
    case "$rel" in /*|'') warn "ignoring unsafe .worktreeinclude entry: $entry"; continue ;; esac

    src="$MAIN_ROOT/$rel"; dst="$WT_ROOT/$rel"
    [ -e "$src" ] || continue
    if [ -e "$dst" ] || [ -L "$dst" ]; then continue; fi
    mkdir -p "$(dirname "$dst")"
    if   [ "$mode" = link ]; then ln -s "$src" "$dst"
    elif [ -d "$src" ];      then cp -a "$src" "$dst"
    else                          cp -p "$src" "$dst"; fi
    log "Inherited from main ($mode): $rel"
    n=$((n + 1))
  done
  if [ "$n" -gt 0 ]; then log "Synchronized $n unversioned item(s) from main checkout."; fi
  return 0
}

# --- 6. Slot & port resolution ------------------------------------------------
read_key() { [ -f "$WT_SLOT_FILE" ] && awk -F= -v k="$1" '$1==k{sub(/^[^=]*=/,""); print; exit}' "$WT_SLOT_FILE"; return 0; }

peer_slots() { # slots claimed by the OTHER worktrees of this repo
  local p
  while IFS= read -r p; do
    [ "$p" = "$WT_ROOT" ] && continue
    if [ -f "$p/.worktree-dev/slot.env" ]; then
      awk -F= '$1=="WT_SLOT"{print $2; exit}' "$p/.worktree-dev/slot.env"
    fi
  done < <(git worktree list --porcelain 2>/dev/null | sed -n 's/^worktree //p')
  return 0
}

allocate_slot() { # first free slot, starting from a hash of the path
  local claimed start i cand span=$((SLOT_COUNT - 1))
  claimed=" $(peer_slots | tr '\n' ' ') "
  start=$(( $(path_hash "$WT_ROOT") % span + 1 ))
  for ((i = 0; i < span; i++)); do
    cand=$(( (start - 1 + i) % span + 1 ))
    case "$claimed" in *" $cand "*) continue ;; esac
    if port_busy $((APP_BASE_PORT + cand)) || port_busy $((DB_BASE_PORT + cand)); then continue; fi
    printf '%s' "$cand"; return 0
  done
  return 1
}

build_db_url() {
  DB_URL=""
  [ -n "$DB_URL_TEMPLATE" ] || return 0
  local u=${DB_URL_TEMPLATE//\{port\}/$DB_PORT}
  u=${u//\{project\}/$PROJECT_NAME}
  DB_URL=${u//\{db\}/${PROJECT_NAME//-/_}}
}

save_state() {
  mkdir -p "$WT_STATE_DIR"
  if [ ! -f "$WT_SLOT_FILE" ] && git check-ignore -q ".worktree-dev/slot.env" 2>/dev/null; then :
  elif [ ! -f "$WT_SLOT_FILE" ] && git rev-parse --git-dir >/dev/null 2>&1; then
    warn ".worktree-dev/ is not git-ignored; add it to .gitignore"
  fi
  {
    echo "WT_SLOT=$WT_SLOT"
    echo "WT_PORT_MODE=$PORT_MODE"
    echo "WT_APP_PORT=$APP_PORT"
    echo "WT_DB_PORT=$DB_PORT"
    echo "COMPOSE_PROJECT_NAME=$WT_COMPOSE_PROJECT"
    echo "$ENV_APP_PORT_NAME=$APP_PORT"
    echo "$ENV_DB_PORT_NAME=$DB_PORT"
    if [ -n "$DB_URL" ]; then echo "$ENV_DB_URL_NAME=$DB_URL"; fi
  } > "$WT_SLOT_FILE"
}

# resolve_slot [port-override]: reuse persisted state; allocate only on first use.
resolve_slot() {
  local override=${1:-} s_slot s_mode s_app s_db
  s_slot=$(read_key WT_SLOT); s_mode=$(read_key WT_PORT_MODE)
  s_app=$(read_key WT_APP_PORT); s_db=$(read_key WT_DB_PORT)

  if [ -n "$s_slot" ] && [ -n "$s_app" ] && [ -n "$s_db" ] && [ -z "$override" ]; then
    WT_SLOT=$s_slot; PORT_MODE=${s_mode:-dynamic}; APP_PORT=$s_app; DB_PORT=$s_db
    build_db_url
    return 0
  fi

  if is_main_worktree; then
    WT_SLOT=0; APP_PORT=$CANONICAL_APP_PORT; DB_PORT=$CANONICAL_DB_PORT; PORT_MODE=dynamic
  else
    WT_SLOT=${s_slot:-$(allocate_slot)} || die "no free slot (1..$((SLOT_COUNT - 1))): check running worktrees or ports"
    APP_PORT=$((APP_BASE_PORT + WT_SLOT)); DB_PORT=$((DB_BASE_PORT + WT_SLOT)); PORT_MODE=dynamic
  fi
  if [ -n "$override" ]; then APP_PORT=$override; PORT_MODE=static; fi
  build_db_url
  save_state
}

export_env() {
  export WT_SLOT WT_APP_PORT="$APP_PORT" WT_DB_PORT="$DB_PORT" COMPOSE_PROJECT_NAME="$WT_COMPOSE_PROJECT"
  export APP_PORT DB_PORT                       # for ${APP_PORT} / ${DB_PORT} in compose files
  export "$ENV_APP_PORT_NAME=$APP_PORT" "$ENV_DB_PORT_NAME=$DB_PORT"
  if [ -n "$DB_URL" ]; then export "$ENV_DB_URL_NAME=$DB_URL"; fi
  return 0
}

have_state() { [ -f "$WT_SLOT_FILE" ]; }

OPT_DETACH=false; OPT_PORT=""; OPT_PURGE=false
parse_opts() {
  while [ $# -gt 0 ]; do
    case "$1" in
      -d|--detach) OPT_DETACH=true ;;
      --purge)     OPT_PURGE=true ;;
      --port)      [ $# -ge 2 ] || die "--port needs a value"; OPT_PORT=$2; shift ;;
      --port=*)    OPT_PORT=${1#--port=} ;;
      *)           die "unknown option: $1" ;;
    esac
    shift
  done
  case "$OPT_PORT" in *[!0-9]*) die "--port must be a number" ;; esac
}

# --- 7. Subcommands -----------------------------------------------------------
cmd_up() {
  parse_opts "$@"
  check_tools
  sync_untracked
  resolve_slot "$OPT_PORT"
  export_env

  if [ -n "$COMPOSE_FILE_PATH" ]; then
    log "Starting dependencies for $WT_COMPOSE_PROJECT (slot $WT_SLOT)..."
    compose up -d ${DB_SERVICE:+"$DB_SERVICE"}
  fi

  if [ -z "$APP_CMD" ]; then
    log "Dependencies ready (WT_APP_CMD not set: app not started). App port: $APP_PORT"
    return 0
  fi
  if app_alive; then log "App already running (pid $(cat "$WT_PID_FILE")) on port $APP_PORT."; return 0; fi
  if port_busy "$APP_PORT"; then
    die "port $APP_PORT is already in use by another process; free it or run: up --port <N>"
  fi

  mkdir -p "$WT_STATE_DIR"
  if [ "$OPT_DETACH" = true ]; then
    log "Starting app in background on port $APP_PORT (log: $WT_LOG_FILE)..."
    # shellcheck disable=SC2016  # $$ / $0 / $1 must expand in the child shell
    if command -v setsid >/dev/null 2>&1; then
      setsid bash -c 'echo $$ > "$0"; exec bash -c "$1"' "$WT_PID_FILE" "$APP_CMD" \
        >>"$WT_LOG_FILE" 2>&1 </dev/null &
    else
      nohup bash -c 'echo $$ > "$0"; exec bash -c "$1"' "$WT_PID_FILE" "$APP_CMD" \
        >>"$WT_LOG_FILE" 2>&1 </dev/null &
    fi
    disown 2>/dev/null || true
    if wait_healthy; then
      log "App is up: http://localhost:$APP_PORT"
    else
      stop_app; die "app failed to start"
    fi
  else
    log "Starting app in foreground on port $APP_PORT (Ctrl+C to quit)..."
    exec bash -c "$APP_CMD"
  fi
}

cmd_stop() {
  have_state || { log "No worktree state here; nothing to stop."; return 0; }
  resolve_slot; export_env
  stop_app
  compose stop || true
}

cmd_down() {
  parse_opts "$@"
  have_state || { log "No worktree state here; nothing to remove."; return 0; }
  resolve_slot; export_env
  stop_app
  if [ "$OPT_PURGE" = true ]; then
    log "Purging containers and volumes for $WT_COMPOSE_PROJECT..."
    compose down -v --remove-orphans || true
    rm -rf "$WT_STATE_DIR"
    log "State removed; slot $WT_SLOT released."
  else
    compose down || true
  fi
}

cmd_sync() { sync_untracked; }

cmd_env() {
  parse_opts "$@"
  resolve_slot "$OPT_PORT"
  echo "export WT_SLOT=\"$WT_SLOT\""
  echo "export $ENV_APP_PORT_NAME=\"$APP_PORT\""
  echo "export $ENV_DB_PORT_NAME=\"$DB_PORT\""
  if [ -n "$DB_URL" ]; then echo "export $ENV_DB_URL_NAME=\"$DB_URL\""; fi
  echo "export COMPOSE_PROJECT_NAME=\"$WT_COMPOSE_PROJECT\""
}

cmd_info() {
  resolve_slot
  local app_state="stopped" db_state="down"
  if app_alive; then app_state="running (pid $(cat "$WT_PID_FILE"))"
  elif port_busy "$APP_PORT"; then app_state="port in use by another process"; fi
  if port_busy "$DB_PORT"; then db_state="listening"; fi
  echo "======================================================================"
  echo " Worktree: $(basename "$WT_ROOT")  [$(is_main_worktree && echo main || echo linked)]"
  echo "======================================================================"
  echo "  Slot       : $WT_SLOT ($PORT_MODE ports)"
  echo "  Project    : $WT_COMPOSE_PROJECT"
  echo "  App        : http://localhost:$APP_PORT  [$app_state]"
  echo "  DB port    : 127.0.0.1:$DB_PORT  [$db_state]"
  echo "  Engine     : $CONTAINER_ENGINE${COMPOSE_FILE_PATH:+ ($(basename "$COMPOSE_FILE_PATH"))}"
  echo "  State dir  : $WT_STATE_DIR"
  echo "======================================================================"
}

cmd_test() {
  have_state || die "no worktree state: run 'up -d' first"
  resolve_slot; export_env
  if [ -n "$TEST_CMD" ]; then
    log "Running WT_TEST_CMD against port $APP_PORT..."
    bash -c "$TEST_CMD"
  elif health_ok; then
    log "OK: app answers on port $APP_PORT"
  else
    die "app does not answer on port $APP_PORT"
  fi
}

# --- 8. CLI dispatcher ---------------------------------------------------------
cmd=${1:-info}; [ $# -gt 0 ] && shift
case "$cmd" in
  up)    cmd_up "$@" ;;
  stop)  cmd_stop ;;
  down)  cmd_down "$@" ;;
  clean) cmd_down --purge ;;
  sync)  cmd_sync ;;
  info)  cmd_info ;;
  env)   cmd_env "$@" ;;
  test)  cmd_test ;;
  -h|--help|help) sed -n '2,/^# ====/p' "$0" | sed 's/^# \{0,1\}//' ;;
  *)     echo "Usage: $0 {up|stop|down|clean|sync|info|env|test} [options]" >&2; exit 1 ;;
esac
